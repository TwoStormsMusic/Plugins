#!/usr/bin/env python3
"""Turn the font files in resources/fonts into src/gui/fonts_data.cpp (byte arrays)."""
import os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
names = ['Regular', 'Medium', 'SemiBold', 'Bold']
out = ['// generated by tools/embed.py from resources/fonts (Inter, SIL OFL 1.1) - do not edit', '#include <cstddef>', 'namespace ts { namespace gui {']
for n in names:
    data = open(os.path.join(root, 'resources/fonts', f'Inter-{n}.otf'), 'rb').read()
    out.append(f'extern const unsigned char font_inter_{n.lower()}[] = {{')
    for i in range(0, len(data), 24):
        out.append(','.join(str(b) for b in data[i:i+24]) + ',')
    out.append('};')
    out.append(f'extern const size_t font_inter_{n.lower()}_size = {len(data)};')
out.append('}}')
open(os.path.join(root, 'src/gui/fonts_data.cpp'), 'w').write('\n'.join(out) + '\n')
print('ok')
